# functools.wraps copied each target's __name__; put the public name back so a
# renamed delegation reads correctly in tracebacks and generated docs. Every
# _delegate() result is a coroutine function carrying __wrapped__, which
# nothing else in the class body is.
for _public_name, _attr in list(vars(RESTMixin).items()):
    if callable(_attr) and hasattr(_attr, "__wrapped__"):
        _attr.__name__ = _public_name
        _attr.__qualname__ = f"RESTMixin.{_public_name}"
