"""RESTMixin: the flat ``bot.<verb>_<resource>()`` surface.

Each attribute is a thin async delegation to a resource module function,
generated by ``_delegate()`` instead of written out, so this file never
holds a hand-maintained copy of every resource signature. ``functools.wraps``
carries the target's docstring and real parameters through to the generated
API reference; the ``__name__`` fixup at the end restores the public name for
the handful of methods that point at a differently named function (e.g.
``fetch_application`` delegates to ``application.fetch_current_application``).

Referencing a function that no longer exists fails at import time here rather
than silently dropping the method.
"""

